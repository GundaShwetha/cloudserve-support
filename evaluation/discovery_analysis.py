"""Stage 1 evidence: every figure in the discovery workbook, computed from the development tickets.

    python -m evaluation.discovery_analysis      # writes docs/discovery_evidence.md

Only development_tickets.json and documentation.json are read. Figures carry their source so each
workbook row can be traced (requirement -> evidence -> this script).
"""
from __future__ import annotations

import json
import statistics as st
from collections import Counter, defaultdict
from pathlib import Path

from src.config import ROOT, Settings

H = lambda t: t["history"]  # noqa: E731
L = lambda t: t["labels"]  # noqa: E731


def pct(k, n):
    return f"{100 * k / n:.1f}%" if n else "n/a"


def seg_table(dev, key, name):
    groups = defaultdict(list)
    for t in dev:
        groups[key(t)].append(t)
    rows = [f"| {name} | n | resolved first contact | escalated | mean CSAT | repeat contact | mean resolution (min) | median (min) | answerable from docs |",
            "|---|---|---|---|---|---|---|---|---|"]
    for g, ts in sorted(groups.items(), key=lambda kv: str(kv[0])):
        n = len(ts)
        rows.append(f"| {g} | {n} | {pct(sum(H(t)['first_contact_resolution'] for t in ts), n)} | "
                    f"{pct(sum(H(t)['escalated'] for t in ts), n)} | {st.mean(H(t)['csat_rating'] for t in ts):.2f} | "
                    f"{pct(sum(H(t)['repeat_contact'] for t in ts), n)} | {st.mean(H(t)['resolution_time_minutes'] for t in ts):.0f} | "
                    f"{st.median(H(t)['resolution_time_minutes'] for t in ts):.0f} | {pct(sum(L(t)['answerable_from_docs'] for t in ts), n)} |")
    return rows


def main() -> None:
    s = Settings()
    dev = json.loads(s.train_path.read_text(encoding="utf-8"))
    docs = json.loads(s.docs_path.read_text(encoding="utf-8"))
    n = len(dev)
    out = ["# Discovery evidence (generated by `python -m evaluation.discovery_analysis`)", "",
           f"Source: `data/development_tickets.json` ({n} tickets) and `data/documentation.json` ({len(docs)} articles). "
           "History fields describe what CloudServe's human operation achieved; labels describe what should have happened.", ""]

    # ---- headline counts
    ans = [t for t in dev if L(t)["answerable_from_docs"]]
    esc = [t for t in dev if H(t)["escalated"]]
    out += ["## E1. Headline figures", "", "| ID | Measure | Figure |", "|---|---|---|",
            f"| E1.1 | Tickets | {n} |",
            f"| E1.2 | Resolved on first contact (history) | {pct(sum(H(t)['first_contact_resolution'] for t in dev), n)} |",
            f"| E1.3 | Escalated (history) | {pct(len(esc), n)} |",
            f"| E1.4 | Mean CSAT (history) | {st.mean(H(t)['csat_rating'] for t in dev):.2f} / 5 |",
            f"| E1.5 | Repeat contact within 7 days (history) | {pct(sum(H(t)['repeat_contact'] for t in dev), n)} |",
            f"| E1.6 | Mean / median resolution time (history) | {st.mean(H(t)['resolution_time_minutes'] for t in dev):.0f} / {st.median(H(t)['resolution_time_minutes'] for t in dev):.0f} min |",
            f"| E1.7 | **Answerable from existing documentation** | **{pct(len(ans), n)}** ({len(ans)}) |",
            f"| E1.8 | **Escalated tickets that were answerable from the documentation** | **{pct(sum(L(t)['answerable_from_docs'] for t in esc), len(esc))}** ({sum(L(t)['answerable_from_docs'] for t in esc)}/{len(esc)}) |",
            f"| E1.9 | Answerable tickets that were nevertheless escalated | {pct(sum(H(t)['escalated'] for t in ans), len(ans))} |",
            f"| E1.10 | Tickets labelled must-not-auto-respond | {pct(sum(L(t)['must_not_auto_respond'] for t in dev), n)} |",
            f"| E1.11 | Expected route auto_respond / escalate | {pct(sum(L(t)['expected_route'] == 'auto_respond' for t in dev), n)} / {pct(sum(L(t)['expected_route'] == 'escalate' for t in dev), n)} |",
            f"| E1.12 | Non-fluent writers | {pct(sum(t['language_fluency'] == 'non_fluent' for t in dev), n)} |",
            f"| E1.13 | Distinct customers / customers with more than one ticket | {len({t['customer_id'] for t in dev})} / {sum(1 for v in Counter(t['customer_id'] for t in dev).values() if v > 1)} |",
            f"| E1.14 | Articles reviewed within the review cycle (`last_reviewed_days_ago` = 0) | {sum(d['last_reviewed_days_ago'] == 0 for d in docs)}/{len(docs)} |", ""]

    # ---- distributions
    for title, key in (("E2. Channel", lambda t: t["channel"]), ("E3. Urgency (label)", lambda t: L(t)["urgency"]),
                       ("E4. Customer tier", lambda t: t["customer_tier"]), ("E5. Language fluency", lambda t: t["language_fluency"]),
                       ("E6. Region", lambda t: t["customer_region"]), ("E7. Answerable from documentation", lambda t: L(t)["answerable_from_docs"])):
        out += [f"## {title}", ""] + seg_table(dev, key, title.split(". ")[1]) + [""]

    # ---- intents: volume vs effort
    total_min = sum(H(t)["resolution_time_minutes"] for t in dev)
    out += ["## E8. Intent: share of volume vs share of effort", "",
            "Effort is approximated by historical resolution minutes (elapsed time, not hands-on time - see limitations).", "",
            "| intent | n | share of volume | share of resolution minutes | answerable | resolved first contact | mean CSAT | must not auto-respond | main article |",
            "|---|---|---|---|---|---|---|---|---|"]
    by_int = defaultdict(list)
    for t in dev:
        by_int[L(t)["intent"]].append(t)
    for it, ts in sorted(by_int.items(), key=lambda kv: -len(kv[1])):
        mins = sum(H(t)["resolution_time_minutes"] for t in ts)
        top_doc = Counter(d for t in ts for d in L(t)["expected_doc_ids"]).most_common(1)
        out.append(f"| {it} | {len(ts)} | {pct(len(ts), n)} | {pct(mins, total_min)} | {pct(sum(L(t)['answerable_from_docs'] for t in ts), len(ts))} | "
                   f"{pct(sum(H(t)['first_contact_resolution'] for t in ts), len(ts))} | {st.mean(H(t)['csat_rating'] for t in ts):.2f} | "
                   f"{'yes' if any(L(t)['must_not_auto_respond'] for t in ts) else 'no'} | {top_doc[0][0] if top_doc else '-'} |")
    ans_min = sum(H(t)["resolution_time_minutes"] for t in ans)
    out += ["", f"Answerable tickets: {pct(len(ans), n)} of volume, {pct(ans_min, total_min)} of resolution minutes. "
            f"Unanswerable: {pct(n - len(ans), n)} of volume, {pct(total_min - ans_min, total_min)} of minutes.", ""]

    # ---- label consistency
    groups = defaultdict(list)
    for t in dev:
        groups[t["body"].strip()].append(t)

    def ceiling(f):
        return sum(Counter(f(t) for t in ts).most_common(1)[0][1] for ts in groups.values()) / n

    out += ["## E9. Text duplication and label consistency", "",
            f"Distinct ticket bodies: {len(groups)} of {n}. Bodies that appear more than once: "
            f"{sum(1 for g in groups.values() if len(g) > 1)} (covering {sum(len(g) for g in groups.values() if len(g) > 1)} tickets).", "",
            "Highest accuracy any system reading only the text could reach (identical texts must get identical predictions):", "",
            "| label | ceiling |", "|---|---|"]
    for name, f in (("intent", lambda t: L(t)["intent"]), ("urgency", lambda t: L(t)["urgency"]),
                    ("answerable_from_docs", lambda t: L(t)["answerable_from_docs"]),
                    ("expected_route", lambda t: L(t)["expected_route"]),
                    ("expected_doc_ids", lambda t: tuple(L(t)["expected_doc_ids"]))):
        out.append(f"| {name} | {ceiling(f):.1%} |")
    out += ["", "## E10. Routing policy implied by the labels", "",
            "| expected_route | answerable | must_not_auto_respond | tickets |", "|---|---|---|---|"]
    for (r, a, m), k in sorted(Counter((L(t)["expected_route"], L(t)["answerable_from_docs"], L(t)["must_not_auto_respond"]) for t in dev).items()):
        out.append(f"| {r} | {a} | {m} | {k} |")
    hi = [t for t in dev if L(t)["answerable_from_docs"] and not L(t)["must_not_auto_respond"] and L(t)["expected_route"] == "escalate"]
    out += ["", f"The {len(hi)} answerable, policy-permitted tickets labelled `escalate` are all urgency=high and intent in "
            f"{sorted({L(t)['intent'] for t in hi})}.", ""]

    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "discovery_evidence.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out[:30]))


if __name__ == "__main__":
    main()

"""Does the non-fluent gap seen on validation also appear on the development data? (fairness option A)

    python -m evaluation.fairness_check        # writes docs/fairness_development.md

Uses 5-fold out-of-fold predictions on development_tickets.json only (the validation set is not used
for tuning). Compares routing quality for fluent and non-fluent tickets with the current thresholds,
and sweeps a separate answerability threshold for non-fluent tickets using the same cost method as
FR-04 (a wrong automatic reply costs WRONG_AUTO_COST x an unnecessary escalation).
"""
from __future__ import annotations

import json
from datetime import datetime, timezone

import numpy as np

from src.config import ROOT, Settings, load_thresholds
from src.ingest import load_tickets
from src.retrieve import Corpus, TfidfBackend, learn_intent_doc_prior
from src.schemas import INCIDENT_INTENTS, NEVER_AUTO_INTENTS
from src.train import WRONG_AUTO_COST, oof_predictions, retrieval_scores


def main() -> None:
    s = Settings()
    th = load_thresholds(s)
    tickets = [t for t in load_tickets(s.train_path) if t.labels.get("intent")]
    oof = oof_predictions(tickets)
    corpus = Corpus.load(s.docs_path)
    best, _ = retrieval_scores(corpus, TfidfBackend(corpus), tickets, oof["intent"], oof["intent_conf"],
                               learn_intent_doc_prior(tickets))
    hits = best >= th.get("retrieval_min_score_by_backend", {}).get("tfidf", th["retrieval_min_score"])
    nf = np.array([t.language_fluency == "non_fluent" for t in tickets])
    should = oof["y_route"] == "auto_respond"
    t_main, t_int = float(th["answerable_probability_min"]), float(th["intent_confidence_min"])

    def route(t_nf: float) -> np.ndarray:
        out = []
        for i in range(len(tickets)):
            it = oof["intent"][i]
            t = t_nf if nf[i] else t_main
            out.append(it not in NEVER_AUTO_INTENTS and not (it in INCIDENT_INTENTS and oof["urgency"][i] == "high")
                       and oof["intent_conf"][i] >= t_int and hits[i] and oof["p_ans"][i] >= t)
        return np.array(out)

    def stats(auto, m):
        a, sh = auto[m], should[m]
        return {"n": int(m.sum()), "routing_accuracy": float((a == sh).mean()), "auto_rate": float(a.mean()),
                "wrong_auto": int((a & ~sh).sum()), "missed": int((~a & sh).sum())}

    base = route(t_main)
    fl, nfs = stats(base, ~nf), stats(base, nf)
    sweep = []
    for t in np.arange(0.30, 0.96, 0.02):
        st = stats(route(float(t)), nf)
        st.update(t=round(float(t), 2), cost=WRONG_AUTO_COST * st["wrong_auto"] + st["missed"])
        sweep.append(st)
    chosen = min(sweep, key=lambda r: (r["cost"], -r["t"]))

    L = ["# Fairness check on development data (generated by `python -m evaluation.fairness_check`)", "",
         f"Generated {datetime.now(timezone.utc).isoformat(timespec='seconds')}. 5-fold out-of-fold predictions on "
         "development_tickets.json; validation data not used.", "",
         f"Current thresholds: answerability >= {t_main}, intent confidence >= {t_int}.", "",
         "| group | tickets | routing accuracy | answered automatically | wrong auto-replies | missed automations |",
         "|---|---|---|---|---|---|",
         f"| fluent | {fl['n']} | {fl['routing_accuracy']:.1%} | {fl['auto_rate']:.1%} | {fl['wrong_auto']} | {fl['missed']} |",
         f"| non-fluent | {nfs['n']} | {nfs['routing_accuracy']:.1%} | {nfs['auto_rate']:.1%} | {nfs['wrong_auto']} | {nfs['missed']} |", "",
         f"Gap (fluent - non-fluent): {100 * (fl['routing_accuracy'] - nfs['routing_accuracy']):+.1f} points.", "",
         "## Option A: a separate answerability threshold for non-fluent tickets", "",
         f"| non-fluent threshold | routing accuracy | answered automatically | wrong | missed | cost ({WRONG_AUTO_COST:g}x) |",
         "|---|---|---|---|---|---|"]
    for r in sweep[::3] + ([chosen] if chosen not in sweep[::3] else []):
        mark = " **(lowest cost)**" if r is chosen else ""
        L.append(f"| {r['t']:.2f}{mark} | {r['routing_accuracy']:.1%} | {r['auto_rate']:.1%} | {r['wrong_auto']} | {r['missed']} | {r['cost']:.0f} |")
    L += ["", f"Lowest-cost non-fluent threshold: {chosen['t']:.2f} (main threshold {t_main}). "
          + ("A stricter threshold for non-fluent tickets is not supported by the development data."
             if chosen["t"] <= t_main else "A stricter threshold for non-fluent tickets is supported by the development data.")]
    out = ROOT / "docs" / "fairness_development.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    (ROOT / "evaluation" / "results").mkdir(exist_ok=True)
    (ROOT / "evaluation" / "results" / "fairness_development.json").write_text(
        json.dumps({"fluent": fl, "non_fluent": nfs, "sweep": sweep, "chosen": chosen}, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
